package com.system.entity;


public class Student {

  private double studentId;
  private long specialityId;
  private double teacherId;
  private String studentPassword;
  private String studentName;
  private long studentGender;
  private double studentPhoneNumber;
  private String studentEmail;
  private double pictureId;


  public double getStudentId() {
    return studentId;
  }

  public void setStudentId(double studentId) {
    this.studentId = studentId;
  }


  public long getSpecialityId() {
    return specialityId;
  }

  public void setSpecialityId(long specialityId) {
    this.specialityId = specialityId;
  }


  public double getTeacherId() {
    return teacherId;
  }

  public void setTeacherId(double teacherId) {
    this.teacherId = teacherId;
  }


  public String getStudentPassword() {
    return studentPassword;
  }

  public void setStudentPassword(String studentPassword) {
    this.studentPassword = studentPassword;
  }


  public String getStudentName() {
    return studentName;
  }

  public void setStudentName(String studentName) {
    this.studentName = studentName;
  }


  public long getStudentGender() {
    return studentGender;
  }

  public void setStudentGender(long studentGender) {
    this.studentGender = studentGender;
  }


  public double getStudentPhoneNumber() {
    return studentPhoneNumber;
  }

  public void setStudentPhoneNumber(double studentPhoneNumber) {
    this.studentPhoneNumber = studentPhoneNumber;
  }


  public String getStudentEmail() {
    return studentEmail;
  }

  public void setStudentEmail(String studentEmail) {
    this.studentEmail = studentEmail;
  }


  public double getPictureId() {
    return pictureId;
  }

  public void setPictureId(double pictureId) {
    this.pictureId = pictureId;
  }

}
